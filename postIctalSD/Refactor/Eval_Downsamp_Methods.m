% size of output feature vector
feat = nan(1,nFreq*nChannel);

% reassign to modelOPs to match closedLoop scripts
modelOPs.freqs = freq;
modelOPs.durFeat = model.ops.durFeat; % 4s feature bins
modelOPs.art_thres = 5e4; % NOTE probably needs to be decreased
modelOPs.features = model.ops.features;
modelOPs.ch_subj = model.ops.ch_subj;
modelOPs.Fs = dFs; % The Fs assigned to modelOPs is the Fs used for 
                   % wavelet transformation, and must match that of 
                   % input data



%% Load data for one epoch to test

