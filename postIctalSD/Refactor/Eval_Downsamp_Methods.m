%%%%
% Test scoring on LFP data generated by subsampling
t1=datetime('now');

dataT=data';
lfp_ds_data = dataT(:,1:round(Fs/dFs):end)';
lfp_ds_feats = modelOPs.features(lfp_ds_data,[],modelOPs);
[lfp_ds_label, lfp_ds_conf] = predict(model.rusTree,lfp_ds_feats);

tlfp_ds=second(datetime('now'))-second(t1);

%%%%
% Test scoring on LFP data generated by convLFP function
t1=datetime('now');

lfp_convds_data=[];
for channel =1:size(data,2);
    lfp_convds_data(:,channel)=convLPFilttest(double(data(:,channel)),dFs/2,Fs,[],Fs/dFs)';
end
lfp_convds_feats = modelOPs.features(lfp_convds_data,[],modelOPs);
[lfp_convds_label,lfp_convds_conf] = predict(model.rusTree,lfp_convds_feats);

tconvds=second(datetime('now'))-second(t1);

%%%%
% Test scoring on LFP data generated by lowpass then downsample functions
t1=datetime('now');

filtdata=[];
lfp_lpds_data=[];

filtdata=lowpass(double(data),modelOPs.Fs/2,20000);
lfp_lpds_data=downsample(filtdata,Fs/dFs);
lfp_lpds_feats = modelOPs.features(lfp_lpds_data,[],modelOPs);
[lfp_lpds_label,lfp_lpds_conf] = predict(model.rusTree,lfp_lpds_feats);
tlpds=second(datetime('now'))-second(t1);

%%%%
% Test scoring on LFP data generated by decimate function
t1=datetime('now');

filtdata=[];
for channel =1:size(data,2)
    filtdata(:,channel) = decimate(double(data(:,channel)),Fs/dFs);
end
lfp_dec_data=filtdata;
lfp_dec_feats = modelOPs.features(lfp_dec_data,[],modelOPs);
[lfp_dec_label,lfp_dec_conf] = predict(model.rusTree,lfp_dec_feats);
tdec=second(datetime('now'))-second(t1);


